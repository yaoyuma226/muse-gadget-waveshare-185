"""Builds components/muse/muse_font_cjk_16.c from GNU Unifont.

unscii 16, the reply font, has a 16 px cell and only ASCII. Unifont's CJK
glyphs are 16 x 16 bitmaps, one cell each, so they make a fallback that keeps
the grid. Takes every GB2312 character from U+2E80 up (Hanzi, CJK and
full-width punctuation, kana), about 7,000 glyphs at 1 bpp.

    curl -O https://unifoundry.com/pub/unifont/unifont-16.0.04/font-builds/unifont-16.0.04.hex.gz
    gunzip unifont-16.0.04.hex.gz
    python3 tools/muse/cjk_font.py unifont-16.0.04.hex components/muse/muse_font_cjk_16.c

Unifont is GPL-2.0+ with the font embedding exception, or OFL-1.1.
"""

import sys

FIRST = 0x2E80   # below this the screen shows ASCII stand-ins (muse_text.h)


def gb2312():
    cps = set()
    for hi in range(0xA1, 0xF8):
        for lo in range(0xA1, 0xFF):
            try:
                ch = bytes([hi, lo]).decode("gb2312")
            except UnicodeDecodeError:
                continue
            if ord(ch) >= FIRST:
                cps.add(ord(ch))
    cps.add(0x3000)   # ideographic space
    return cps


def main(hex_path, out_path):
    want = gb2312()
    glyphs = {}
    with open(hex_path) as f:
        for line in f:
            cp, _, bits = line.strip().partition(":")
            cp = int(cp, 16)
            if cp in want and len(bits) == 64:   # 16 x 16; skip any 8-wide one
                glyphs[cp] = bytes.fromhex(bits)
    cps = sorted(glyphs)
    start = cps[0]
    assert cps[-1] - start < 0x10000, "one sparse cmap holds 16-bit offsets"

    out = []
    w = out.append
    w("/* Generated by tools/muse/cjk_font.py from GNU Unifont 16.0.04")
    w(" * (GPL-2.0+ with the font embedding exception, or OFL-1.1). Do not edit.")
    w(f" * {len(cps)} GB2312 glyphs, 16 x 16, 1 bpp: the reply font's CJK fallback. */")
    w('#include "lvgl.h"')
    w("")
    w("static const uint8_t glyph_bitmap[] = {")
    for cp in cps:
        w("    " + ",".join(f"0x{b:02x}" for b in glyphs[cp]) + f",  /* U+{cp:04X} */")
    w("};")
    w("")
    w("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {")
    w("    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},   /* id 0 reserved */")
    for i in range(len(cps)):
        w(f"    {{.bitmap_index = {i * 32}, .adv_w = 256, .box_w = 16, .box_h = 16, .ofs_x = 0, .ofs_y = 0}},")
    w("};")
    w("")
    w("static const uint16_t unicode_list[] = {")
    for i in range(0, len(cps), 16):
        w("    " + ",".join(f"0x{cp - start:04x}" for cp in cps[i:i + 16]) + ",")
    w("};")
    w("")
    w("static const lv_font_fmt_txt_cmap_t cmaps[] = {")
    w(f"    {{.range_start = 0x{start:04X}, .range_length = 0x{cps[-1] - start + 1:04X}, .glyph_id_start = 1,")
    w(f"     .unicode_list = unicode_list, .glyph_id_ofs_list = NULL, .list_length = {len(cps)},")
    w("     .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY},")
    w("};")
    w("")
    w("static const lv_font_fmt_txt_dsc_t font_dsc = {")
    w("    .glyph_bitmap = glyph_bitmap,")
    w("    .glyph_dsc = glyph_dsc,")
    w("    .cmaps = cmaps,")
    w("    .kern_dsc = NULL,")
    w("    .kern_scale = 0,")
    w("    .cmap_num = 1,")
    w("    .bpp = 1,")
    w("    .kern_classes = 0,")
    w("    .bitmap_format = 0,")
    w("};")
    w("")
    w("/* Same metrics as lv_font_unscii_16, so its glyphs sit on the same lines. */")
    w("const lv_font_t muse_font_cjk_16 = {")
    w("    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,")
    w("    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,")
    w("    .line_height = 17,")
    w("    .base_line = 0,")
    w("    .subpx = LV_FONT_SUBPX_NONE,")
    w("    .dsc = &font_dsc,")
    w("};")
    with open(out_path, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"{len(cps)} glyphs, U+{start:04X}..U+{cps[-1]:04X}, {len(cps) * 32} bitmap bytes")


if __name__ == "__main__":
    main(*sys.argv[1:3])
